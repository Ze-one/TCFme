function rowsToQuestions(rows: Row[], skill: Skill): Question[] {
  return rows.map((r, i) => {
    const id = `${skill}-${i + 1}`;
    answers[id] = { correct: r[4], rationale: r[5] };
    return {
      id,
      skill,
      position: i + 1,
      level: levels[i],
      title: r[0],
      passage: r[1],
      prompt: r[2],
      options: r[3],
      ...(skill === "listening" ? { audio_path: `${id}.mp3` } : {}),
    };
  });
}
